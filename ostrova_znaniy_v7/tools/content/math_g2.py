def t_table(r):
    t = []
    facts = r.sample([(a, b) for a in range(2, 10) for b in range(2, 10)], 6)
    for a, b in facts[:3]:
        t.append(inp(f"Вычисли: {a} · {b}", a * b, f"{a} · {b} = {a*b}.", "Вспомни таблицу умножения."))
    for a, b in facts[3:5]:
        t.append(inp(f"Вычисли: {a*b} : {a}", b, f"{a*b} : {a} = {b}, потому что {a} · {b} = {a*b}.", "Деление — обратное умножению."))
